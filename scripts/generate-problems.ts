// Regenerates src/data/problems.ts from NeetCode's own data:
//   - neetcode.io's app bundle: the NeetCode 250 list in roadmap order, topic, difficulty,
//     both slugs (NeetCode's often differ from LeetCode's), solution video, NeetCode 150 flag;
//   - NeetCode's GitHub repo: which problems are LeetCode Premium.
//
//   npm run generate:problems
//
// Then review `git diff src/data/problems.ts`: progress is keyed by LeetCode number, so renamed or
// re-slugged problems are harmless, but a problem dropped from the list loses its place in the UI.

import { writeFile } from 'node:fs/promises'

const SITE = 'https://neetcode.io/'
const GITHUB_DATA = 'https://raw.githubusercontent.com/neetcode-gh/leetcode/main/.problemSiteData.json'
const OUT = new URL('../src/data/problems.ts', import.meta.url)
const DIFFICULTIES = ['Easy', 'Medium', 'Hard']

type Fields = Record<string, string | number | boolean>

interface SiteProblem {
  problem: string
  pattern: string
  difficulty: string
  code: string
  link: string
  ncLink: string
  video: string
  neetcode150?: boolean
  premiumAlgo100?: boolean
}

async function fetchText(url: string): Promise<string> {
  const res = await fetch(url, { headers: { 'User-Agent': 'Mozilla/5.0 (leetcode-tracker problem list generator)' } })
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`)
  return res.text()
}

/** The site is an Angular app; its problem list ships inside the content-hashed main bundle. */
async function siteProblems(): Promise<SiteProblem[]> {
  const html = await fetchText(SITE)
  const main = html.match(/src="(main\.\w+\.js)"/)?.[1]
  if (!main) throw new Error("Couldn't find the main bundle on neetcode.io — the page layout changed.")
  const bundle = await fetchText(new URL(main, SITE).href)
  // Minified object literals: {problem:"Two Sum",pattern:"Arrays & Hashing",…,neetcode250:!0}
  const objects = (bundle.match(/\{problem:"[^{}]*?\}/g) ?? []).map(parseObject)
  const seen = new Set<unknown>()
  return objects.filter((o): o is Fields & SiteProblem => {
    if (o.neetcode250 !== true || seen.has(o.code)) return false
    seen.add(o.code)
    return true
  })
}

/** Reads the string, `!0`/`!1` and number fields of one minified object literal — data only, nothing is evaluated. */
function parseObject(source: string): Fields {
  const fields: Fields = {}
  for (const [, key, str, literal] of source.slice(1, -1).matchAll(/(\w+):(?:"((?:[^"\\]|\\.)*)"|(!0|!1|\d+))/g)) {
    if (str !== undefined) fields[key] = unescape(str)
    else fields[key] = literal === '!0' ? true : literal === '!1' ? false : Number(literal)
  }
  return fields
}

function unescape(str: string): string {
  try {
    return JSON.parse(`"${str}"`) as string
  } catch {
    return str
  }
}

const slug = (link: string) => link.replace(/^\/+|\/+$/g, '')

async function premiumSlugs(): Promise<Set<string>> {
  const data = JSON.parse(await fetchText(GITHUB_DATA)) as { link: string; premium?: boolean }[]
  return new Set(data.filter((p) => p.premium).map((p) => slug(p.link)))
}

/** Fail loudly rather than write a half-broken list if NeetCode's data changes shape. */
function check(problems: SiteProblem[]) {
  const problems250 = problems.length
  const ids = new Set(problems.map((p) => p.code.split('-')[0]))
  const core = problems.filter((p) => p.neetcode150).length
  const errors = [
    problems250 !== 250 && `expected 250 problems, found ${problems250}`,
    ids.size !== problems250 && 'duplicate LeetCode numbers',
    core !== 150 && `expected 150 NeetCode 150 problems, found ${core}`,
    ...problems.flatMap((p) => [
      !/^\d+-/.test(p.code) && `${p.problem}: no LeetCode number in "${p.code}"`,
      !DIFFICULTIES.includes(p.difficulty) && `${p.problem}: unknown difficulty "${p.difficulty}"`,
      !(p.link && p.ncLink && p.video && p.pattern) && `${p.problem}: missing a slug, video or topic`,
    ]),
  ].filter(Boolean)
  if (errors.length > 0) throw new Error(`NeetCode's data doesn't look right:\n  ${errors.join('\n  ')}`)
}

function render(problems: SiteProblem[], premium: Set<string>): string {
  const q = (s: string) => JSON.stringify(s)
  const topics = [...new Set(problems.map((p) => p.pattern))]
  const rows = problems.map((p) => {
    const fields = [
      `id: ${Number(p.code.split('-')[0])}`,
      `title: ${q(p.problem)}`,
      `topic: ${q(p.pattern)}`,
      `difficulty: '${p.difficulty}'`,
      `leetcode: ${q(slug(p.link))}`,
      `neetcode: ${q(slug(p.ncLink))}`,
      `video: ${q(p.video)}`,
    ]
    if (premium.has(slug(p.link)) || p.premiumAlgo100) fields.push('premium: true')
    if (p.neetcode150) fields.push('core: true')
    return `  { ${fields.join(', ')} },`
  })

  return `// Generated by scripts/generate-problems.ts from neetcode.io's NeetCode 250 list — rerun it, don't edit by hand.
// \`id\` is the LeetCode problem number.

export const TOPICS = [
${topics.map((t) => `  ${q(t)},`).join('\n')}
] as const

export type Topic = (typeof TOPICS)[number]
export type Difficulty = 'Easy' | 'Medium' | 'Hard'

export interface Problem {
  id: number
  title: string
  topic: Topic
  difficulty: Difficulty
  /** leetcode.com/problems/<slug> */
  leetcode: string
  /** neetcode.io/problems/<slug> — often differs from the LeetCode slug */
  neetcode: string
  /** LeetCode Premium only; free to solve on NeetCode */
  premium?: true
  /** NeetCode's YouTube solution video id */
  video: string
  /** Part of the core NeetCode 150 */
  core?: true
}

export const PROBLEMS: Problem[] = [
${rows.join('\n')}
]

/** Every problem by its LeetCode number — build lookups from this, not from PROBLEMS again. */
export const problemById: ReadonlyMap<number, Problem> = new Map(PROBLEMS.map((p) => [p.id, p]))

export const leetcodeUrl = (p: Problem) => \`https://leetcode.com/problems/\${p.leetcode}/\`
export const videoUrl = (p: Problem) => \`https://www.youtube.com/watch?v=\${p.video}\`
export const neetcodeUrl = (p: Problem) => \`https://neetcode.io/problems/\${p.neetcode}?list=neetcode250\`
`
}

const [problems, premium] = await Promise.all([siteProblems(), premiumSlugs()])
check(problems)
await writeFile(OUT, render(problems, premium))
const count = (pred: (p: SiteProblem) => boolean) => problems.filter(pred).length
console.log(
  `Wrote ${problems.length} problems in ${new Set(problems.map((p) => p.pattern)).size} topics ` +
    `(${count((p) => Boolean(p.neetcode150))} core, ${count((p) => premium.has(slug(p.link)) || Boolean(p.premiumAlgo100))} premium) to src/data/problems.ts`,
)
